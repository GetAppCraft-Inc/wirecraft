"""Generate src/styles/tokens.css and src/lib/icons.ts from design/generator/lib.py (the design source of truth).

    python3 scripts/gen-design-tokens.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "design", "generator"))
import lib  # noqa: E402


def var(name):
    return "--" + name.replace("/", "-")


def block(sel, mode):
    out = [sel + " {"]
    for _, items in lib.TOKENS:
        for name, dark, light, _ in items:
            out.append("  %s: %s;" % (var(name), (dark, light)[mode]))
    out.append("}")
    return "\n".join(out)


css = ["/* Generated by scripts/gen-design-tokens.py from design/generator/lib.py — do not edit. */",
       block(":root, [data-theme='dark']", 0), "", block("[data-theme='light']", 1), "", ":root {"]
for i in range(1, 13):
    css.append("  --space-%d: %dpx;" % (i * 4, i * 4))
for nm, v in [("xs", 3), ("sm", 4), ("md", 6), ("lg", 8), ("xl", 12), ("full", 999)]:
    css.append("  --radius-%s: %dpx;" % (nm, v))
for nm, v in [("row", 24), ("row-compact", 20), ("control", 28), ("control-sm", 22), ("toolbar", 44), ("statusbar", 24)]:
    css.append("  --size-%s: %dpx;" % (nm, v))
for k, eff in lib.SHADOW.items():
    e = eff[0]
    c = e["color"]
    rgba = "rgba(0,0,0,%.2f)" % (int(c[7:9], 16) / 255)
    css.append("  --shadow-%d: %dpx %dpx %dpx %s;" % (k, e["offset"][0], e["offset"][1], e["radius"], rgba))
css.append("}")
os.makedirs(os.path.join(ROOT, "src", "styles"), exist_ok=True)
with open(os.path.join(ROOT, "src", "styles", "tokens.css"), "w") as f:
    f.write("\n".join(css) + "\n")

with open(os.path.join(ROOT, "src", "lib", "icons.ts"), "w") as f:
    f.write("// Generated by scripts/gen-design-tokens.py from design/generator/lib.py — do not edit.\n")
    f.write("export const ICONS = " + json.dumps(lib.ICON_SRC, indent=2) + " as const;\n")
    f.write("export type IconName = keyof typeof ICONS;\n")
print("ok")
